import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync('cmd/razvilka/web/node-browser.js','utf8');
const start=source.indexOf('// BEGIN NODE MEASUREMENT MODEL'),end=source.indexOf('// END NODE MEASUREMENT MODEL');
const context=vm.createContext({Date,Promise,Object,Number,Array,Infinity});
vm.runInContext(source.slice(start,end)+'\nglobalThis.model=nodeMeasurementModel;',context);
const model=context.model,at='2026-10-31T10:00:00Z';
const job={mode:'service',timing:{version:1,enqueued_at:at,first_admitted_at:'2026-10-31T10:00:02Z',observed_at:'2026-10-31T10:00:08Z',queue_wait_ms:2000,total_ms:5000,total_kind:'enqueue-to-server-completion'},results:[{duration_ms:3000,stages:[{id:'configuration',duration_ms:500},{id:'cleanup',duration_ms:200}]}]};
const text=model.jobTiming(job,17);
assert.match(text,/До первого допуска: 2000 мс/);
assert.match(text,/до завершения на сервере: 5000 мс/);
assert.match(text,/включая очистку\): 3000 мс/);
assert.match(text,/Очистка 200 мс/);
assert.match(text,/панели: 17 мс \(отдельно от времени сервера\)/);
const startup=model.jobTiming({...job,results:[{duration_ms:9000,stages:[{id:'runtime_start',duration_ms:3},{id:'runtime_ready',duration_ms:8000},{id:'route_identity',duration_ms:2}]}]},null);
assert.match(startup,/Запуск движка 3 мс/);
assert.match(startup,/Готовность SOCKS 8000 мс/);
assert.match(startup,/Идентичность маршрута 2 мс/);
assert.match(startup,/не сумма/);
assert.equal(model.jobTiming({},null),'');
assert.match(model.jobTiming({...job,timing:{...job.timing,queue_wait_ms:null,first_admitted_at:undefined}},null),/время не наблюдалось/);
assert.doesNotMatch(model.jobTiming({...job,timing:{...job.timing,queue_wait_ms:null,first_admitted_at:undefined}},null),/До первого допуска: 0/);
assert.match(model.jobTiming({...job,timing:{...job.timing,queue_wait_ms:0}},0),/До первого допуска: <1 мс/);
assert.doesNotMatch(model.jobTiming({...job,timing:{...job.timing,total_ms:-1}},NaN),/завершения на сервере:|Чтение результата/);
console.log('node job queue/total/readback timing: OK');
const phases = [{sequence:1,kind:'service-http',status:'failed',tls:{observed:true,duration_us:1234,status:'complete'},ttfb:{observed:true,duration_us:3210,status:'incomplete'},socks_connect:{observed:true,duration_us:0,status:'multiple'},body_read:{observed:false,duration_us:0}}];
const network = model.jobTiming({...job,results:[{network_timings:phases}]},null);
assert.match(network,/TLS: 1.2 мс \(завершён\)/);
assert.match(network,/До первого байта: 3.2 мс \(не завершён\)/);
assert.match(network,/SOCKS: подключение и согласование: несколько попыток/);
assert.match(network,/Чтение ответа: не наблюдалось/);
assert.match(network,/не подтверждают работу сервиса или LAN/);
assert.doesNotMatch(network,/SOCKS[^·]*0 мс/);
assert.equal(model.networkTiming([{...phases[0],kind:'<private>'}]),'');
assert.doesNotMatch(model.networkTiming([{...phases[0],tls:{observed:true,duration_us:Infinity,status:'<secret>'}}]),/secret|Infinity/);
assert.equal((model.networkTiming(Array.from({length:40},(_,i)=>({...phases[0],sequence:i+1}))).match(/Обмен /g)||[]).length,32);
assert.doesNotMatch(model.jobTiming({...job,mode:'connectivity',results:[{network_timings:phases}]},null),/Обмен/);
console.log('node network timing: bounded original observations and incomplete/multiple/absent labels OK');
