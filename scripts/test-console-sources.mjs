import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {sourceCard,sourceDate,sourceStatusLabel}=require('../cmd/razvilka/web/console-autonomy.js');
const source={source_id:'feed-oneoff',name:'Разовый источник',saved:false,enabled:false,status:'synced',imported:2,last_success_at:'2026-10-18T01:02:00Z'};
const oneoff=sourceCard(source,'Europe/Moscow');
assert.match(oneoff,/Разовое получение · не сохранено/);
assert.match(oneoff,/data-feed-add/);
assert.doesNotMatch(oneoff,/data-feed-form|data-feed-sync|name="interval"|Таймер выключен/);
const saved=sourceCard({...source,saved:true},'UTC');
assert.match(saved,/data-feed-form="feed-oneoff"/);
assert.match(saved,/data-feed-sync="feed-oneoff"/);
assert.match(saved,/Таймер выключен/);
assert.doesNotMatch(saved,/data-feed-add/);
assert.match(sourceCard({...source,saved:true,enabled:true}),/Таймер включён/);
assert.doesNotMatch(sourceCard({...source,saved:undefined}),/data-feed-form/);
assert.match(oneoff,/04:02 \(Europe\/Moscow\)/);
assert.match(saved,/01:02 \(UTC\)/);
assert.equal(sourceDate('0001-01-01T00:00:00Z'),'Ещё нет');
assert.equal(sourceDate('bad'),'Ещё нет');
assert.equal(sourceDate(source.last_success_at,'Invalid/Zone'),source.last_success_at.replace('Z','.000Z'));
assert.equal(sourceStatusLabel('synced'),'Получено');
assert.equal(sourceStatusLabel('needs_acceptance'),'Нужно подтвердить частичный результат');
assert.equal(sourceStatusLabel('unrecognized-private-payload'),'Неизвестный результат');
assert.equal(sourceStatusLabel('toString'),'Неизвестный результат');
assert.equal(sourceStatusLabel(''),'Ожидается');
assert.doesNotMatch(sourceCard({...source,name:'<img onerror="bad">'}),/<img/);
console.log('PASS source cards: one-off versus saved actions, explicit timezone, localized statuses, escaped values');
