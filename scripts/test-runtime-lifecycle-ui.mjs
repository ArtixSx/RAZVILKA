import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync('cmd/razvilka/web/interface.js','utf8');
const start=source.indexOf('// BEGIN RUNTIME LIFECYCLE PRESENTATION'),end=source.indexOf('// END RUNTIME LIFECYCLE PRESENTATION');
assert.ok(start>=0&&end>start);
const context=vm.createContext({});vm.runInContext(source.slice(start,end)+'\nglobalThis.present=engineLifecyclePresentation;',context);
const present=context.present;
assert.equal(present({}).known,false);
assert.equal(present({lifecycle:{schema:2,operations:{live_apply:{registration:'registered',available:true}}}}).known,false);
const value=present({lifecycle:{schema:1,operations:{live_apply:{registration:'registered',available:null},native_validation:{registration:'unknown'},installer:{registration:'absent',available:false},import_export:{registration:'lab-only'}},prerequisites:['Нужен модуль ядра']}});
assert.equal(value.known,true);
assert.match(value.rows.join(' '),/условия запуска ещё проверяются/);
assert.match(value.rows.join(' '),/регистрация не подтверждена/);
assert.match(value.rows.join(' '),/исполнитель не подключён/);
assert.match(value.rows.join(' '),/только лаборатория/);
assert.doesNotMatch(value.rows.join(' '),/работает|готов|здоров/);
assert.equal(value.prerequisites[0],'Нужен модуль ядра');
assert.match(source,/engineLifecycleDetails\(info\.engine\)/);
const sidecar=present({lifecycle:{schema:1,operations:{runtime_preflight:{registration:'registered',available:null},sidecar_runtime:{registration:'registered',available:null},sidecar_recovery:{registration:'registered',available:null},native_validation:{registration:'absent',available:false},live_apply:{registration:'absent',available:false}}}});
assert.match(sidecar.rows.join(' '),/Проверка версии и владения runtime/);
assert.match(sidecar.rows.join(' '),/TUN-зависимость родительского маршрута/);
assert.match(sidecar.rows.join(' '),/Нативная проверка конфига: исполнитель не подключён/);
assert.match(sidecar.rows.join(' '),/Применение маршрута: исполнитель не подключён/);
assert.doesNotMatch(sidecar.rows.join(' '),/работает|готов|здоров/);
console.log('runtime lifecycle presentation: OK');
