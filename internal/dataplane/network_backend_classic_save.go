package dataplane

import (
	"slices"
	"strconv"
	"strings"
	"time"
	"unicode/utf8"
)

// Parse only the researched legacy 1.8.10/1.8.11 complete save grammar. The
// same upstream print_rule4/6 functions emit -S and save rules; preserve those
// bytes verbatim. Only save's timestamps and counters (absent from -S) vanish.
// This conversion is not a source, inventory or effect authorization.
func backendClassicSaveTables(data []byte, expected []string, family int) ([][]byte, error) {
	if family < 0 || family > 1 || len(expected) > backendClassicTables || len(data) > backendClassicBytes || !utf8.Valid(data) {
		return nil, errBackendInventory
	}
	if len(expected) == 0 {
		if len(data) != 0 {
			return nil, errBackendInventory
		}
		return nil, nil
	}
	if len(data) == 0 || data[len(data)-1] != '\n' || strings.Count(string(data), "\n") > backendClassicRows+4*backendClassicTables {
		return nil, errBackendInventory
	}
	for i, name := range expected {
		if !backendClassicTableName(name) || slices.Contains(expected[:i], name) {
			return nil, errBackendInventory
		}
	}
	images := make(map[string][]byte, len(expected))
	state, table, rules := 0, "", false
	var body []byte
	var chains map[string]bool
	for _, line := range strings.Split(string(data[:len(data)-1]), "\n") {
		if len(line) > 16384 || strings.IndexFunc(line, func(c rune) bool { return c < 32 && c != '\t' || c == 127 }) >= 0 {
			return nil, errBackendInventory
		}
		switch state {
		case 0:
			program := []string{"iptables-save", "ip6tables-save"}[family]
			date := ""
			for _, version := range []string{"1.8.10", "1.8.11"} {
				if rest, ok := strings.CutPrefix(line, "# Generated by "+program+" v"+version+" on "); ok {
					date = rest
				}
			}
			if _, err := time.Parse(time.ANSIC, date); err != nil {
				return nil, errBackendInventory
			}
			state = 1
		case 1:
			if !strings.HasPrefix(line, "*") || !slices.Contains(expected, line[1:]) {
				return nil, errBackendInventory
			}
			table = line[1:]
			if _, exists := images[table]; exists {
				return nil, errBackendInventory
			}
			body, chains, rules, state = nil, map[string]bool{}, false, 2
		case 2:
			if line == "COMMIT" {
				if len(chains) == 0 {
					return nil, errBackendInventory
				}
				images[table], state = body, 3
				continue
			}
			if strings.HasPrefix(line, ":") {
				f := strings.Split(line[1:], " ")
				if rules || len(f) != 3 || chains[f[0]] || !classicSaveCounters(f[2]) {
					return nil, errBackendInventory
				}
				converted := "-P " + f[0] + " " + f[1]
				if f[1] == "-" {
					converted = "-N " + f[0]
					if f[2] != "[0:0]" {
						return nil, errBackendInventory
					}
				}
				if _, err := backendXTablesRowTokens(converted); err != nil {
					return nil, err
				}
				chains[f[0]] = true
				body = append(body, converted...)
			} else {
				tokens, err := backendXTablesRowTokens(line)
				if err != nil || tokens[0] != "-A" || !chains[tokens[1]] {
					return nil, errBackendInventory
				}
				rules = true
				body = append(body, line...)
			}
			body = append(body, '\n')
		case 3:
			date, ok := strings.CutPrefix(line, "# Completed on ")
			if _, err := time.Parse(time.ANSIC, date); !ok || err != nil {
				return nil, errBackendInventory
			}
			state = 0
		}
	}
	if state != 0 || len(images) != len(expected) {
		return nil, errBackendInventory
	}
	result := make([][]byte, len(expected))
	for i, name := range expected {
		result[i] = images[name]
	}
	return result, nil
}

func classicSaveCounters(value string) bool {
	if len(value) < 5 || value[0] != '[' || value[len(value)-1] != ']' {
		return false
	}
	pair := strings.Split(value[1:len(value)-1], ":")
	if len(pair) != 2 {
		return false
	}
	for _, value := range pair {
		n, err := strconv.ParseUint(value, 10, 64)
		if err != nil || strconv.FormatUint(n, 10) != value {
			return false
		}
	}
	return true
}
