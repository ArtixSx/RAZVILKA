func classicSaveTestImage(family int, table, body string) string {
	return "# Generated by " + []string{"iptables-save", "ip6tables-save"}[family] + " v1.8.10 on Mon Nov  9 12:00:00 2026\n*" + table + "\n" + body + "COMMIT\n# Completed on Mon Nov  9 12:00:01 2026\n"
}

func TestBackendClassicSavePreservesExactRowsAndOrder(t *testing.T) {
	const rules = "-A CUSTOM -p tcp -m comment --comment \"quote \\\" and \\\\ slash\" -j RETURN\n-A OUTPUT -j CUSTOM\n"
	for family := range 2 {
		body := ":OUTPUT DROP [18446744073709551615:25]\n:CUSTOM - [0:0]\n" + rules
		input := classicSaveTestImage(family, "mangle", body) + classicSaveTestImage(family, "filter", ":INPUT ACCEPT [7:8]\n")
		got, err := backendClassicSaveTables([]byte(input), []string{"filter", "mangle"}, family)
		if err != nil || len(got) != 2 || string(got[0]) != "-P INPUT ACCEPT\n" || string(got[1]) != "-P OUTPUT DROP\n-N CUSTOM\n"+rules {
			t.Fatal("row bytes/order lost", got, err)
		}
		other := strings.ReplaceAll(input, "[18446744073709551615:25]", "[0:99]")
		other = strings.ReplaceAll(other, "12:00:00", "12:00:02")
		again, err := backendClassicSaveTables([]byte(other), []string{"filter", "mangle"}, family)
		if err != nil || !slices.Equal(got[1], again[1]) {
			t.Fatal("counter/time leaked into structural comparison", err)
		}
	}
}

func TestBackendClassicSaveRejectsIncompleteOrAmbiguousGrammar(t *testing.T) {
	valid := classicSaveTestImage(0, "filter", ":OUTPUT ACCEPT [0:0]\n:USER - [0:0]\n-A OUTPUT -j USER\n")
	cases := map[string]string{
		"truncated":        strings.TrimSuffix(valid, "\n"),
		"missing-commit":   strings.Replace(valid, "COMMIT\n", "", 1),
		"duplicate-commit": strings.Replace(valid, "COMMIT\n", "COMMIT\nCOMMIT\n", 1),
		"duplicate-table":  valid + valid,
		"extra-table":      valid + classicSaveTestImage(0, "raw", ":PREROUTING ACCEPT [0:0]\n"),
		"duplicate-chain":  strings.Replace(valid, ":USER - [0:0]\n", ":USER - [0:0]\n:USER - [0:0]\n", 1),
		"late-chain":       strings.Replace(valid, "COMMIT\n", ":LATE - [0:0]\nCOMMIT\n", 1),
		"undefined-chain":  strings.Replace(valid, "-A OUTPUT", "-A MISSING", 1),
		"foreign-command":  strings.Replace(valid, "-A OUTPUT -j USER", "-F OUTPUT", 1),
		"unknown-comment":  strings.Replace(valid, "COMMIT\n", "# skipped?\nCOMMIT\n", 1),
		"unknown-header":   strings.Replace(valid, "v1.8.10", "v1.8.12", 1),
		"wrong-family":     strings.Replace(valid, "iptables-save", "ip6tables-save", 1),
		"bad-counter":      strings.Replace(valid, "[0:0]", "[18446744073709551616:0]", 1),
		"user-counter":     strings.Replace(valid, ":USER - [0:0]", ":USER - [1:0]", 1),
		"quote":            strings.Replace(valid, "-j USER", "-m comment --comment \"unterminated -j USER", 1),
		"tail":             valid + "-A OUTPUT -j DROP\n",
		"empty-table":      classicSaveTestImage(0, "filter", ""),
		"oversize":         strings.Repeat("x", backendClassicBytes+1),
	}
	for name, input := range cases {
		t.Run(name, func(t *testing.T) {
			if _, err := backendClassicSaveTables([]byte(input), []string{"filter"}, 0); err == nil {
				t.Fatal("accepted malformed complete image")
			}
		})
	}
	for _, names := range [][]string{nil, {"filter", "filter"}, {"filter", "mangle"}} {
		if _, err := backendClassicSaveTables([]byte(valid), names, 0); err == nil {
			t.Fatal("accepted wrong table set", names)
		}
	}
	if result, err := backendClassicSaveTables(nil, nil, 1); err != nil || len(result) != 0 {
		t.Fatal("empty registered family", err)
	}
}

type backendInventorySaveModel struct {
	backendInventoryTestRunner
	save func(context.Context, netidentity.Identity, string, [2]string, int, [2][]string) ([2][]byte, bool, error)
}

func (m backendInventorySaveModel) ReadBoundedClassicInventory(c context.Context, id netidentity.Identity, review string, paths [2]string, limit int, tables [2][]string) ([2][]byte, bool, error) {
	return m.save(c, id, review, paths, limit, tables)
}

func TestBackendClassicSaveRetainsBookendsAndRefusesPartialFallback(t *testing.T) {
	for _, mode := range []string{"complete", "unsupported", "partial-error", "unsupported-with-output", "body-drift", "registration-drift", "cancelled", "raw-budget"} {
		t.Run(mode, func(t *testing.T) {
			r, scope, p, nft, order := backendInventoryTestFixture(t)
			base := r.Runner.(backendInventoryTestRunner)
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			calls := 0
			originalError := errors.New("original save failed")
			r.Runner = backendInventorySaveModel{base, func(_ context.Context, id netidentity.Identity, review string, paths [2]string, limit int, tables [2][]string) (raw [2][]byte, supported bool, err error) {
				calls++
				if id != scope.Network || review != scope.ToolReviewID || paths != [2]string{r.IPTables, r.IP6Tables} || limit <= 0 || limit > backendClassicBytes {
					t.Fatal("original scope changed")
				}
				if mode == "unsupported" {
					return raw, false, nil
				}
				for family := range tables {
					for _, table := range tables[family] {
						raw[family] = append(raw[family], classicSaveTestImage(family, table, ":OUTPUT ACCEPT [0:0]\n")...)
					}
				}
				switch mode {
				case "partial-error":
					return raw, true, originalError
				case "unsupported-with-output":
					return raw, false, nil
				case "body-drift":
					if calls == 2 {
						raw[0] = []byte(strings.ReplaceAll(string(raw[0]), "ACCEPT", "DROP"))
					}
				case "cancelled":
					cancel()
				case "raw-budget":
					raw[0] = make([]byte, limit+1)
				}
				return raw, true, nil
			}}
			if mode == "registration-drift" {
				p.registeredTables = func(context.Context, int) ([]byte, error) {
					if calls > 0 {
						return []byte("filter\n"), nil
					}
					return []byte("filter\nmangle\n"), nil
				}
			}
			got, err := r.read(ctx, scope, p)
			if mode == "complete" || mode == "unsupported" {
				if err != nil || got.requireLANBackendCoverage() != nil || calls != 2 || nft.generationCalls != 2 || nft.closed != 1 {
					t.Fatal("complete image/bookend lost", calls, err)
				}
				checks, names := 0, 0
				for _, event := range *order {
					if event == "tools" {
						checks++
					}
					if strings.HasPrefix(event, "names") {
						names++
					}
				}
				if checks != 2 || names != 8 {
					t.Fatal("closing checks skipped", checks, names)
				}
			} else {
				if err == nil || got.requireLANBackendCoverage() == nil || nft.closed != 1 {
					t.Fatal("partial save escaped", err)
				}
				if mode == "partial-error" && !errors.Is(err, originalError) {
					t.Fatal("producer cause hidden", err)
				}
				if mode == "cancelled" && !errors.Is(err, context.Canceled) {
					t.Fatal("cancellation hidden", err)
				}
			}
		})
	}
}
